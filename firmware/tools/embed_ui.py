# PlatformIO pre-build step: gzip web/index.html into src/ui_gz.h so the
# ESP32 can serve the phone app straight from flash.
import gzip
import os

try:
    Import("env")  # noqa: F821  (provided by PlatformIO)
    root = env["PROJECT_DIR"]  # noqa: F821
except NameError:
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

src = os.path.join(root, "web", "index.html")
dst = os.path.join(root, "src", "ui_gz.h")

with open(src, "rb") as f:
    data = gzip.compress(f.read(), 9, mtime=0)

lines = []
for i in range(0, len(data), 20):
    lines.append("  " + ",".join(str(b) for b in data[i:i + 20]) + ",")

out = (
    "// Generated by tools/embed_ui.py from web/index.html. Do not edit.\n"
    "#pragma once\n#include <Arduino.h>\n\n"
    f"static const size_t kUiGzLen = {len(data)};\n"
    "static const uint8_t kUiGz[] PROGMEM = {\n" + "\n".join(lines) + "\n};\n"
)

old = open(dst).read() if os.path.exists(dst) else None
if out != old:
    with open(dst, "w") as f:
        f.write(out)
    print(f"embed_ui: wrote {dst} ({len(data)} bytes gzip)")
